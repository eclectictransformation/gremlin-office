#!/usr/bin/env python3
"""Regenerate supabase/migrations/20261025050200_gw_seed.sql from world-data.json.
Run again (and apply the output as a new migration) whenever rooms/eggs/socks/badges/games/guestbook lines change.
The seed is idempotent: it upserts whitelists and never touches players, scores or guestbook rows."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W = json.load(open(os.path.join(ROOT, "world-data.json")))
q = lambda s: "'" + str(s).replace("'", "''") + "'"

# caps for personal bests (clamped) and ranked boards (rejected above). Ranked caps sit just above
# the best score the game can actually produce (see README-world.md).
CAPS = {"desk-tennis": 999, "paper-plane-toss": 6, "stapler-stack": 500, "hungry-vine": 500, "sock-pairing": 999,
        "seed-packet-bonk": 9999, "coffee-relay": 6000, "jam-buster": 5000, "desk-duel": 99}
games = []
for mid, m in W["arcade"]["machines"].items():
    for g in m["games"]:
        games.append((g["id"], mid, bool(g.get("ranked")), CAPS.get(g["id"], 9999), g.get("best") == "low"))

known = []
for rid, r in W["rooms"].items():
    known.append(("room", rid))
    for it in r.get("items", []):
        if it["type"] == "sock": known.append(("sock", it["id"]))
        if it["type"] == "egg": known.append(("egg", it["id"]))
for b in W["badges"]["list"]: known.append(("badge", b["id"]))

ADJ = """soggy fuzzy sleepy wobbly crunchy dusty sparkly cozy tiny grumpy jolly lumpy misty nifty peppy quiet rusty silly snug
sunny toasty velvet wiggly zesty bouncy breezy chilly cuddly dizzy fluffy giddy humble itchy jumpy kindly lucky mellow
muddy nimble plucky puffy rumpled shiny sneaky speedy squishy sticky stripy tidy twinkly witty yawning bashful crispy
dapper fancy frosty gentle golden hasty minty noble polite rosy salty spotty swift tangy thrifty tufty curly""".split()
THING = """teacup sock stapler kettle biscuit pickle muffin noodle crumpet pebble acorn mitten button pancake teapot lantern
pillow marble pumpkin sprout radish turnip walnut waffle yogurt beanbag carrot cookie donut eraser feather goblet hammock
inkwell jellybean ladle mushroom napkin paperclip pretzel quill raisin satchel spoon thimble trumpet umbrella vase whistle
bagel candle cushion dumpling envelope fern gumdrop honeybun kazoo lemon meatball nutmeg oatcake parsnip""".split()
VERB = """waltz shuffle tango boogie twirl hop skip wiggle sway prance scoot jig foxtrot polka mambo bop cartwheel tiptoe
spin bounce glide shimmy strut stomp jive salsa twist rumba conga hustle leap frolic caper skedaddle meander mosey
pirouette rollick scamper trot wobble zigzag dawdle doodle giggle hum nap ramble snooze tumble whirl yodel sashay""".split()
for lst in (ADJ, THING, VERB):
    assert all(re.fullmatch(r"[a-z]{3,10}", w) for w in lst), [w for w in lst if not re.fullmatch(r"[a-z]{3,10}", w)]

RULES = {
 # substring = rude anywhere in the letters-only name (careful: 'rape' would block 'grape', so it's a word rule)
 "substring": """fuck shit cunt bitch nigg fagg retard whore slut rapist penis vagina dick porn nazi hitler twat wank
 bollock bastard chink kike dyke tranny pussy asshole boob molest incest jizz""".split(),
 "word": "ass arse anal sex cum hoe tits tit fag poo pee butt nude naked kill die hate rape spic cock pedo semen kkk".split(),
 "reserved_exact": "grimble noodle pip moth dot vesper nancy gremlin gremlins staff system support root owner mod guest player anonymous null undefined".split(),
 "reserved_contains": "bryan admin moderator official grokbot supabase".split(),
}

out = ["-- Gremlin World seed data (whitelists). GENERATED by tools/make-gw-seed.py from world-data.json; safe to re-run.",
       "-- It never touches players, sessions, progress, scores or guestbook entries.", ""]
out.append("insert into gw.games (game_id, machine, ranked, max_score, low) values")
out.append(",\n".join("  (%s, %s, %s, %d, %s)" % (q(a), q(b), str(c).lower(), d, str(e).lower()) for a, b, c, d, e in games))
out.append("on conflict (game_id) do update set machine = excluded.machine, ranked = excluded.ranked, max_score = excluded.max_score, low = excluded.low;\n")
out.append("insert into gw.known_ids (kind, id) values")
out.append(",\n".join("  (%s, %s)" % (q(k), q(i)) for k, i in known))
out.append("on conflict do nothing;\n")
out.append("insert into gw.key_words (slot, word) values")
rows = [(1, w) for w in ADJ] + [(2, w) for w in THING] + [(3, w) for w in VERB]
out.append(",\n".join("  (%d, %s)" % (s, q(w)) for s, w in rows))
out.append("on conflict do nothing;\n")
out.append("insert into gw.name_rules (kind, term) values")
out.append(",\n".join("  (%s, %s)" % (q(k), q(t)) for k, ts in RULES.items() for t in ts))
out.append("on conflict do nothing;\n")
out.append("insert into gw.guestbook_phrases (id, phrase) values")
out.append(",\n".join("  (%d, %s)" % (p["id"], q(p["text"])) for p in W["guestbook"]["phrases"]))
out.append("on conflict (id) do update set phrase = excluded.phrase;\n")
out.append("insert into gw.guestbook_stamps (id, emoji, label) values")
out.append(",\n".join("  (%s, %s, %s)" % (q(s["id"]), q(s["emoji"]), q(s["label"])) for s in W["guestbook"]["stamps"]))
out.append("on conflict (id) do update set emoji = excluded.emoji, label = excluded.label;")
path = os.path.join(ROOT, "supabase", "migrations", "20261025050200_gw_seed.sql")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path, len(games), "games", len(known), "ids", len(rows), "words (%d keys possible)" % (len(ADJ) * len(THING) * len(VERB)))
